let language = "fr";
try {
  if (localStorage.getItem("vyneros.language") === "en") language = "en";
} catch {
  /* Storage may be disabled. */
}
const locale = () => (language === "en" ? "en-GB" : "fr-FR");
function t(key, values = {}) {
  let message = messages[language][key] || messages.fr[key] || key;
  if (Array.isArray(message)) message = message[values.count === 1 ? 0 : 1];
  return message.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}
function translateDocument() {
  document.documentElement.lang = language;
  document.title = "Match Analyse";
  for (const [attribute, target] of [
    ["data-i18n", null],
    ["data-i18n-aria", "aria-label"],
    ["data-i18n-title", "title"],
  ]) {
    document.querySelectorAll(`[${attribute}]`).forEach((element) => {
      const value = t(element.getAttribute(attribute));
      if (target) element.setAttribute(target, value);
      else element.textContent = value;
    });
  }
  document
    .querySelectorAll("[data-language]")
    .forEach((button) =>
      button.setAttribute(
        "aria-pressed",
        String(button.dataset.language === language),
      ),
    );
}
